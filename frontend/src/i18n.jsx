const I18nContext = createContext(null);

const getInitialLanguage = () => {
  const saved = localStorage.getItem(LANGUAGE_KEY);
  return saved === 'zh' || saved === 'en' ? saved : 'en';
};

const formatMessage = (message, values = {}) =>
  message.replace(/\{(\w+)\}/g, (_, key) =>
    Object.prototype.hasOwnProperty.call(values, key) ? values[key] : `{${key}}`
  );

const translateEnglish = (key, values) =>
  formatMessage(dictionaries.en[key] ?? key, values);

export const I18nProvider = ({ children }) => {
  const [language, setLanguageState] = useState(getInitialLanguage);

  const value = useMemo(() => {
    const setLanguage = (nextLanguage) => {
      const normalized = nextLanguage === 'zh' ? 'zh' : 'en';
      localStorage.setItem(LANGUAGE_KEY, normalized);
      setLanguageState(normalized);
    };

    const t = (key, values) => {
      const message = dictionaries[language][key] ?? dictionaries.en[key] ?? key;
      return formatMessage(message, values);
    };

    return {
      language,
      setLanguage,
      toggleLanguage: () => setLanguage(language === 'en' ? 'zh' : 'en'),
      t,
    };
  }, [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};

export const useI18n = () => {
  const context = useContext(I18nContext);
  if (!context) {
    return {
      language: 'en',
      setLanguage: () => {},
      toggleLanguage: () => {},
      t: translateEnglish,
    };
  }
  return context;
};
